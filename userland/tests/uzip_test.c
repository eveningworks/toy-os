#define LOREM_DATA_AT 97   // the deflated member's first data byte

static int write_file(const char *path, const unsigned char *b, size_t n) {
    int fd = open(path, O_WRONLY | O_CREAT | O_TRUNC);
    if (fd < 0) return -1;
    int ok = write(fd, b, n) == (long)n;
    close(fd);
    return ok ? 0 : -1;
}

static long read_file(const char *path, char *buf, size_t cap) {
    int fd = open(path, O_RDONLY);
    if (fd < 0) return -1;
    long n = read(fd, buf, cap);
    close(fd);
    return n;
}

static int listed, list_ok = 1;
static int list_one(void *ctx, const char *name, unsigned long size, unsigned long packed,
                    unsigned d, unsigned t) {
    (void)ctx; (void)d; (void)t;
    if (listed == 0) list_ok &= !strcmp(name, "hello.txt") && size == 15 && packed == 15;
    if (listed == 1) list_ok &= !strcmp(name, "dir/lorem.txt") && size == 1807 && packed == 74;
    listed++;
    return 0;
}

static int progress_calls;
static int count(void *ctx, unsigned long done, unsigned long total) {
    (void)ctx; (void)done; (void)total;
    progress_calls++;
    return 0;
}
static int stop_now(void *ctx, unsigned long done, unsigned long total) {
    (void)ctx; (void)done; (void)total;
    return 1;
}

int main(void) {
    utest_begin("uzip_test", "one zip member out to a file", 0);
    static char buf[4096], err[160];
    const char *zip = "/var/tmp/uzip_test.zip", *out = "/var/tmp/uzip_test.out";
    mkdir("/var", 0755);
    mkdir("/var/tmp", 0755);
    utest_check(write_file(zip, ZIP, sizeof ZIP) == 0, "the archive was written");

    int rc = uzip_extract(zip, "hello.txt", out, 0, 0, err, sizeof err);
    long n = read_file(out, buf, sizeof buf);
    utest_check_detail(rc == 0 && n == 15 && !memcmp(buf, "Hello, toy-os!\n", 15),
                       "a STORED member comes out byte for byte", err);

    progress_calls = 0;
    rc = uzip_extract(zip, "dir/lorem.txt", out, count, 0, err, sizeof err);
    n = read_file(out, buf, sizeof buf);
    int lorem_ok = n == 1807 && !memcmp(buf, "The quick brown fox", 19) &&
                   !memcmp(buf + 1800, "toy-os\n", 7);
    utest_check_detail(rc == 0 && lorem_ok, "a DEFLATED member inflates to its 1807 bytes", err);
    utest_check(progress_calls > 0, "...and progress is reported");

    // THE LISTING: both members, in the directory's order, with the sizes
    // Python's writer recorded -- including the deflated one's packed size.
    listed = 0;
    rc = uzip_list(zip, list_one, 0, err, sizeof err);
    utest_checkf(rc == 0 && listed == 2 && list_ok,
                 "the listing names both members with their sizes (%d listed)", listed);

    rc = uzip_extract(zip, "nope.txt", out, 0, 0, err, sizeof err);
    utest_check_detail(rc == -ENOENT, "a member that is not there is -ENOENT", err);

    unlink(out);
    rc = uzip_extract(zip, "dir/lorem.txt", out, stop_now, 0, err, sizeof err);
    utest_check(rc == -EINTR && access(out, F_OK) != 0, "a stopped extract is -EINTR and leaves nothing");

    // A flipped byte inside the deflate stream: a wrong CRC, or a stream
    // that no longer decodes -- -EINVAL either way, and no file.
    static unsigned char bad[sizeof ZIP];
    memcpy(bad, ZIP, sizeof ZIP);
    bad[LOREM_DATA_AT + 30] ^= 0x10;
    write_file(zip, bad, sizeof bad);
    rc = uzip_extract(zip, "dir/lorem.txt", out, 0, 0, err, sizeof err);
    utest_check_detail(rc == -EINVAL && access(out, F_OK) != 0,
                       "a damaged member is refused and leaves no file", err);

    write_file(zip, ZIP, 20);   // not an archive at all
    rc = uzip_extract(zip, "hello.txt", out, 0, 0, err, sizeof err);
    utest_check_detail(rc == -EINVAL, "a file with no end record is refused", err);

    unlink(zip);
    return utest_end();
}
