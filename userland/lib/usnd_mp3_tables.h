// usnd_mp3_tables.h -- the data ISO/IEC 11172-3 defines for Layer III.
//
// Separated from usnd_mp3.c because it is DATA and that file is LOGIC:
// nothing here is a decision anybody made about this OS, and mixing a
// thousand constants into the decoder would bury the twelve stages that
// are worth reading.
//
// **THREE OF THESE CANNOT BE COMPUTED, ONLY LOOKED UP** -- the Huffman
// codes, the 512-tap synthesis window, and the scalefactor band edges.
// They are the standard's own tables. Everything else a decoder needs
// IS derivable and is derived at runtime in usnd_mp3.c rather than
// frozen here: the alias coefficients from ci[], the intensity ratios
// from tan(i*pi/12), the IMDCT windows from sin(). A table is what you
// write when there is no formula, not a place to cache one.
//
// The Huffman tables are verified structurally by usnd_mp3_selftest():
// every one must be a COMPLETE PREFIX CODE (Kraft sum exactly 1) over
// exactly dim*dim pairs. That check found a real transcription error
// while these were being assembled, and it needs no reference to run --
// which is why it ships rather than living in the tool that built this.
