def rows_to_bytes(rows):
    out = []
    for r in rows:
        assert len(r) == 8, f"row must be 8 wide, got {len(r)}: {r!r}"
        b = 0
        for i, ch in enumerate(r):
            if ch == '#':
                b |= 1 << (7 - i)
        out.append(b)
    assert len(out) == 8
    return out


def emit_c(path):
    lines = []
    lines.append("// 8x8 monochrome bitmap font, ASCII 32-126.")
    lines.append("// Original glyph designs authored for this project.")
    lines.append("// GENERATED by tools/genfont.py -- edit the ASCII art there, not this file.")
    lines.append('#include "font8x8.h"')
    lines.append("")
    lines.append("const unsigned char font8x8_basic[95][8] = {")
    for code in range(32, 127):
        ch = chr(code)
        rows = GLYPHS[ch]
        bs = rows_to_bytes(rows)
        hexes = ", ".join(f"0x{b:02X}" for b in bs)
        label = "'\\''" if ch == "'" else ("'\\\\'" if ch == "\\" else f"'{ch}'")
        lines.append(f"    {{ {hexes} }}, // {code} {label}")
    lines.append("};")
    lines.append("")
    with open(path, "w") as f:
        f.write("\n".join(lines))


def render_preview(path, scale=3):
    from PIL import Image, ImageDraw
    samples = [
        "The quick brown fox jumps",
        "over the lazy dog 0123456789",
        "toy-os graphics mode is up.",
        "Framebuffer + PS/2 mouse +",
        "GRUB GUI OS Welcome about",
        "help clear time uptime echo",
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ",
        "abcdefghijklmnopqrstuvwxyz",
        "!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~",
    ]
    cw, chh = 8 * scale, 8 * scale
    width = max(len(s) for s in samples) * cw
    height = len(samples) * chh
    img = Image.new("RGB", (width, height), (0, 0, 0))
    d = ImageDraw.Draw(img)
    for row, s in enumerate(samples):
        for col, ch in enumerate(s):
            rows = GLYPHS.get(ch)
            if rows is None:
                continue
            for gy in range(8):
                for gx in range(8):
                    if rows[gy][gx] == '#':
                        x0 = col * cw + gx * scale
                        y0 = row * chh + gy * scale
                        d.rectangle([x0, y0, x0 + scale - 1, y0 + scale - 1],
                                    fill=(230, 230, 230))
    img.save(path)


if __name__ == "__main__":
    missing = [chr(c) for c in range(32, 127) if chr(c) not in GLYPHS]
    if missing:
        raise SystemExit(f"missing glyphs: {missing}")
    for ch, rows in GLYPHS.items():
        assert len(rows) == 8, f"{ch!r} must have 8 rows"
    render_preview("/root/toy-os/font_preview.png")
    emit_c("/root/toy-os/kernel/drivers/font8x8.c")
    print("ok: preview + kernel/drivers/font8x8.c written")
